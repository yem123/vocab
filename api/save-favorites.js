const GITHUB_API = "https://api.github.com";
const FILE_PATH = "src/data/favoriteVocabulary.js";
const BRANCH = "main";

const buildFileContent = (words) => {
  const body = JSON.stringify(words, null, 2);
  return `// Auto-generated by the app's "Save" button. Do not edit by hand.
export const FAVORITE_VOCABULARY = ${body};
`;
};

export default async function handler(req, res) {
  if (req.method !== "POST") {
    return res.status(405).json({ error: "Method not allowed" });
  }

  const { password, words } = req.body || {};

  if (!password || password !== process.env.SAVE_PASSWORD) {
    return res.status(401).json({ error: "Incorrect password" });
  }
  if (!Array.isArray(words)) {
    return res.status(400).json({ error: "No words provided" });
  }

  const owner = process.env.GITHUB_OWNER;
  const repo = process.env.GITHUB_REPO;
  const headers = {
    Authorization: `Bearer ${process.env.GITHUB_TOKEN_VOCAB}`,
    Accept: "application/vnd.github+json",
    "User-Agent": "vocab-app",
  };

  try {
    // Look up the file's current sha (required by GitHub to update an existing file)
    let sha;
    const getRes = await fetch(
      `${GITHUB_API}/repos/${owner}/${repo}/contents/${FILE_PATH}?ref=${BRANCH}`,
      { headers },
    );
    if (getRes.ok) {
      const existing = await getRes.json();
      sha = existing.sha;
    } else if (getRes.status !== 404) {
      const errText = await getRes.text();
      console.error("GitHub GET error:", getRes.status, errText);
      return res.status(502).json({ error: "Could not reach GitHub" });
    }

    const content = buildFileContent(words);
    const base64Content = Buffer.from(content, "utf-8").toString("base64");

    const putRes = await fetch(
      `${GITHUB_API}/repos/${owner}/${repo}/contents/${FILE_PATH}`,
      {
        method: "PUT",
        headers: { ...headers, "Content-Type": "application/json" },
        body: JSON.stringify({
          message: `Update favorite vocabulary (${words.length} words)`,
          content: base64Content,
          branch: BRANCH,
          ...(sha ? { sha } : {}),
        }),
      },
    );

    if (!putRes.ok) {
      const errText = await putRes.text();
      console.error("GitHub PUT error:", putRes.status, errText);
      return res.status(502).json({ error: "Could not save to GitHub" });
    }

    return res.status(200).json({ success: true, count: words.length });
  } catch (err) {
    console.error("save-favorites error:", err);
    return res.status(500).json({ error: "Unexpected error" });
  }
}
