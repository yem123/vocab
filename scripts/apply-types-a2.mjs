const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith("--"));
if (!file) { console.log("Usage: node apply-types-a2.mjs <file.js> [--force] [--dry]"); process.exit(1); }
const force = args.includes("--force"), dry = args.includes("--dry");

const text = fs.readFileSync(file, "utf8");
const parts = text.split(/(?=\n[ \t]*\{[ \t]*\r?\n[ \t]*id:[ \t]*\d+,)/);
let added = 0, replaced = 0, skipped = 0, phr = 0, words = 0;
const out = parts.map((blk) => {
  if (!/\n[ \t]*id:[ \t]*\d+,/.test(blk)) return blk;
  const m = blk.match(/\n([ \t]*)level:[^\n]*\n/);
  if (!m) return blk;
  const wm = blk.match(/\n[ \t]*word:[ \t]*(?:\r?\n[ \t]*)?(["'])((?:\\.|(?!\1).)*)\1/);
  const word = wm ? wm[2].replace(/\\"/g, '"') : "";
  const type = PHRASES.has(word) ? "phrase" : "word";
  const has = /\n[ \t]*type:[ \t]*["'][^\n]*\n/.test(blk);
  if (has && !force) { skipped++; return blk; }
  if (type === "phrase") phr++; else words++;
  if (has) { replaced++; return blk.replace(/(\n[ \t]*)type:[ \t]*["'][^\n]*?(\r?\n)/, `$1type: "${type}",$2`); }
  added++;
  return blk.replace(/(\n[ \t]*level:[^\n]*?)(\r?\n)/, `$1$2${m[1]}type: "${type}",$2`);
});
console.log(`${path.basename(file)}: ${added} added, ${replaced} replaced, ${skipped} skipped. word=${words} phrase=${phr}`);
if (dry || added + replaced === 0) process.exit(0);
fs.writeFileSync(file + ".bak", text);
fs.writeFileSync(file, out.join(""));
console.log("Backup: " + file + ".bak");
